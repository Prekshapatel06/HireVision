const db = require('../config/db');
const multer = require('multer');
const path = require('path');
const fs = require('fs');

const storage = multer.diskStorage({
  destination: function (req, file, cb) {
    const uploadDir = path.join(__dirname, '..', 'uploads');
    if (!fs.existsSync(uploadDir)) {
      fs.mkdirSync(uploadDir, { recursive: true });
    }
    cb(null, uploadDir);
  },
  filename: function (req, file, cb) {
    const uniqueSuffix = req.user.id + '-' + Date.now();
    cb(null, 'resume-' + uniqueSuffix + path.extname(file.originalname));
  }
});

const fileFilter = (req, file, cb) => {
  if (file.mimetype === 'application/pdf') {
    cb(null, true);
  } else {
    cb(new Error('Invalid file type, only PDF is allowed!'), false);
  }
};

const upload = multer({
  storage: storage,
  fileFilter: fileFilter,
  limits: { fileSize: 10 * 1024 * 1024 } // 10MB limit
}).single('resume');

exports.getProfile = async (req, res) => {
  try {
    const profileResult = await db.query(
      `SELECT p.*, u.email 
       FROM profiles p
       JOIN users u ON p.user_id = u.id
       WHERE p.user_id = $1`,
      [req.user.id]
    );

    if (profileResult.rowCount === 0) {
      return res.status(404).json({ message: 'Profile not found.' });
    }

    await db.query(
      "UPDATE users SET last_login_at = COALESCE(last_login_at, CURRENT_TIMESTAMP), last_login_role = 'candidate' WHERE id = $1",
      [req.user.id]
    );

    return res.status(200).json(profileResult.rows[0]);
  } catch (err) {
    console.error('Error fetching profile:', err);
    return res.status(500).json({ message: 'Server error retrieving profile.' });
  }
};

exports.updateProfile = async (req, res) => {
  const {
    full_name,
    phone,
    dob,
    gender,
    address,
    city,
    state,
    country,
    profile_photo,
    career_objective,
    education,
    skills,
    projects,
    internships,
    experience,
    certifications,
    achievements,
    languages,
    social_profiles
  } = req.body;

  try {
    const profileResult = await db.query('SELECT id FROM profiles WHERE user_id = $1', [req.user.id]);
    
    if (profileResult.rowCount === 0) {
      await db.query(
        'INSERT INTO profiles (user_id) VALUES ($1)',
        [req.user.id]
      );
    }

    const updateResult = await db.query(
      `UPDATE profiles SET
        full_name = $1,
        phone = $2,
        dob = $3,
        gender = $4,
        address = $5,
        city = $6,
        state = $7,
        country = $8,
        profile_photo = $9,
        career_objective = $10,
        education = $11,
        skills = $12,
        projects = $13,
        internships = $14,
        experience = $15,
        certifications = $16,
        achievements = $17,
        languages = $18,
        social_profiles = $19,
        updated_at = CURRENT_TIMESTAMP
      WHERE user_id = $20
      RETURNING *`,
      [
        full_name || null,
        phone || null,
        dob || null,
        gender || null,
        address || null,
        city || null,
        state || null,
        country || null,
        profile_photo || null,
        career_objective || null,
       
        JSON.stringify(education || []),
        JSON.stringify(skills || {}),
        JSON.stringify(projects || []),
        JSON.stringify(internships || []),
        JSON.stringify(experience || []),
        JSON.stringify(certifications || []),
        JSON.stringify(achievements || []),
        JSON.stringify(languages || []),
        JSON.stringify(social_profiles || {}),
        req.user.id
      ]
    );

    await db.query(
      "UPDATE users SET last_login_at = CURRENT_TIMESTAMP, last_login_role = 'candidate' WHERE id = $1",
      [req.user.id]
    );

    return res.status(200).json({
      message: 'Profile updated successfully',
      profile: updateResult.rows[0]
    });

  } catch (err) {
    console.error('Error updating profile:', err);
    return res.status(500).json({ message: 'Server error updating profile data.' });
  }
};

